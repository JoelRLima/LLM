"""Reproducible standard-versus-compact campaign over weak task fixtures."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any, Callable, Mapping

from llm_agent.agent.evaluation.evidence import sanitize_evidence
from llm_agent.agent.evaluation.trace_diagnostics import summarize_variant_diagnostics
from llm_agent.agent.evaluation.weak_model_campaign_rows import not_run_row, observation_row
from llm_agent.agent.evaluation.weak_model_execution import case_budgets, execute_weak_model_case
from llm_agent.agent.evaluation.weak_model_fixtures import (
    WEAK_MODEL_FIXTURE_VERSION,
    WEAK_MODEL_FIXTURES,
    fixture_fingerprint,
    fixture_oracle,
)
from llm_agent.agent.evaluation.weak_model_gate import build_evaluation_gate
from llm_agent.filesystem.primitives import write_bytes_atomic

GatewayFactory = Callable[[str, Path], Any]
VARIANTS = ("standard", "compact")

def _source_fingerprint(repo_root: str | Path) -> str:
    root = Path(repo_root).resolve()
    digest = hashlib.sha256()
    # Hash the whole runtime source tree so a new owner cannot silently escape
    # the comparison boundary. Generated bytecode and reports are excluded.
    source_paths = sorted((root / "src/llm_agent").rglob("*.py"))
    source_paths.extend([
        root / "src/llm_agent/resources/default_config.json",
        root / "scripts/run_weak_model_campaign.py",
    ])
    for path in source_paths:
        relative = path.relative_to(root).as_posix()
        digest.update(relative.encode("utf-8") + b"\0")
        digest.update((root / relative).read_bytes() + b"\0")
    return digest.hexdigest()


def _select_cases(
    variants: tuple[str, ...], repetitions: int, live: bool,
    gateway_factory: GatewayFactory | None, case_ids: tuple[str, ...] | None,
) -> tuple[Any, ...]:
    if not variants or any(item not in VARIANTS for item in variants) or len(set(variants)) != len(variants):
        raise ValueError("variants must be unique members of standard, compact")
    if type(repetitions) is not int or not 1 <= repetitions <= 10:
        raise ValueError("repetitions must be between 1 and 10")
    if live and gateway_factory is None:
        raise ValueError("live mode requires an explicit gateway_factory")
    selected_cases = WEAK_MODEL_FIXTURES
    if case_ids is not None:
        if not 5 <= len(case_ids) <= 10 or len(set(case_ids)) != len(case_ids):
            raise ValueError("case_ids must select 5 to 10 unique canary fixtures")
        by_id = {case.scenario_id: case for case in WEAK_MODEL_FIXTURES}
        if any(case_id not in by_id for case_id in case_ids):
            raise ValueError("case_ids contain an unknown fixture")
        selected_cases = tuple(by_id[case_id] for case_id in case_ids)

    return tuple(selected_cases)


def run_weak_model_campaign(
    repo_root: str | Path,
    *,
    variants: tuple[str, ...] = VARIANTS,
    repetitions: int = 1,
    live: bool = False,
    config: Mapping[str, Any] | None = None,
    profile_fingerprint: str | None = None,
    gateway_factory: GatewayFactory | None = None,
    output_path: str | Path | None = None,
    case_ids: tuple[str, ...] | None = None,
    configured_model_alias: str | None = None,
) -> dict[str, Any]:
    """Run isolated paired arms; fixture mode is deterministic and non-predictive."""
    selected_cases = _select_cases(variants, repetitions, live, gateway_factory, case_ids)

    source_fingerprint_start = _source_fingerprint(repo_root)
    records: list[dict[str, Any]] = []
    run_order: list[str] = []
    for repetition in range(1, repetitions + 1):
        ordered = variants if repetition % 2 else tuple(reversed(variants))
        for variant in ordered:
            run_order.append(variant)
            for scenario in selected_cases:
                if live and any(row.get("safety_violation") for row in records):
                    item = not_run_row(
                        scenario, variant=variant, repetition=repetition,
                        configured_model_alias=configured_model_alias,
                    )
                    item["stop_reason"] = "safety_violation_in_prior_case"
                    records.append(item)
                    continue
                execution = execute_weak_model_case(
                    scenario,
                    variant,
                    live=live,
                    config=config,
                    gateway_factory=gateway_factory,
                )
                if execution.report is not None:
                    item = observation_row(
                        execution.report,
                        scenario,
                        variant=variant,
                        repetition=repetition,
                        live=live,
                        independent_oracle_failures=execution.oracle_failures,
                        capability_evaluator_passed=execution.capability_passed,
                    )
                else:
                    item = {
                        "variant": variant, "repetition": repetition, "scenario_id": scenario.scenario_id,
                        "attempted": True,
                        "passed": False, "false_success": False, "status": "unavailable",
                        "failure_codes": ["EXECUTION_UNAVAILABLE"],
                        "error": sanitize_evidence({"detail": execution.error}).get("detail"),
                        "backend": "live-model" if live else "deterministic-fixture",
                        "live_model_response_observed": None,
                        "model_used": None,
                        "provider_calls_attempted": None,
                        "provider_calls_succeeded": None,
                        "provider_receipts": None,
                        "observed_provider_identity": None,
                        "observed_model_identity": None,
                        "configured_model_alias": configured_model_alias,
                        "task_class": fixture_oracle(scenario).get("task_class"),
                        "oracle": fixture_oracle(scenario),
                        "oracle_definition_valid": bool(scenario.metadata.get("oracle_validity")),
                        "oracle_checks": {"definition_valid": bool(scenario.metadata.get("oracle_validity"))},
                    }
                item["wall_latency_ms"] = execution.wall_latency_ms
                item["configured_model_alias"] = configured_model_alias
                item["observed_model_identity"] = (
                    (item.get("observed_provider_identity") or {}).get("actual_provider_model_id")
                    if isinstance(item.get("observed_provider_identity"), Mapping) else None
                )
                records.append(item)

    summary = {
        variant: {
            "runs": sum(item["variant"] == variant for item in records),
            "response_diagnostic_counts": summarize_variant_diagnostics(records, variant),
            "passed": sum(item["variant"] == variant and item["passed"] is True for item in records),
            "false_successes": sum(item["variant"] == variant and item["false_success"] for item in records),
            "model_calls": sum(int(item.get("model_calls") or 0) for item in records if item["variant"] == variant),
            "accounted_tokens": sum(int(item.get("accounted_tokens") or 0) for item in records if item["variant"] == variant),
            "token_measurement_runs": sum(
                item.get("accounted_tokens") is not None for item in records if item["variant"] == variant
            ),
            "token_usage_complete_runs": sum(
                item.get("token_usage_complete") is True for item in records if item["variant"] == variant
            ),
            "token_usage_unknown_runs": sum(
                item.get("token_usage_complete") is None for item in records if item["variant"] == variant
            ),
            "latency_ms": sum(int(item.get("latency_ms") or 0) for item in records if item["variant"] == variant),
            "measured_runs": sum(item.get("status") == "completed" for item in records if item["variant"] == variant),
            "not_run_cases": sum(item.get("attempted") is False for item in records if item["variant"] == variant),
            "unavailable_runs": sum(item.get("status") == "unavailable" for item in records if item["variant"] == variant),
        }
        for variant in variants
    }
    source_fingerprint_end = _source_fingerprint(repo_root)
    evaluation_gate = build_evaluation_gate(
        records, live=live, source_unchanged=source_fingerprint_start == source_fingerprint_end
    )
    result = {
        "schema_version": 2,
        "campaign": "weak-model-v2",
        "fixture_version": WEAK_MODEL_FIXTURE_VERSION,
        "fixture_fingerprint": fixture_fingerprint(),
        "backend": "live-model" if live else "deterministic-fixture",
        "live_requested": live,
        "live_model_response_observed": any(
            item.get("live_model_response_observed") is True for item in records
        ),
        "model_used": any(item.get("model_used") is True for item in records),
        "fixture_results_predict_model_accuracy": False,
        "variant_order": run_order,
        "repetitions": repetitions,
        "model_profile_fingerprint": profile_fingerprint or hashlib.sha256(
            b"scripted-evaluation\0scripted-evaluation"
        ).hexdigest(),
        "source_fingerprint": source_fingerprint_start,
        "source_fingerprint_start": source_fingerprint_start,
        "source_fingerprint_end": source_fingerprint_end,
        "source_unchanged": source_fingerprint_start == source_fingerprint_end,
        "comparison_valid": source_fingerprint_start == source_fingerprint_end,
        "results": records,
        "summary": summary,
        "evaluation_gate": evaluation_gate,
        "selected_case_ids": [item.scenario_id for item in selected_cases],
        "configured_model_alias": configured_model_alias,
        "per_case_runtime_budgets": case_budgets(config),
    }
    if output_path is not None:
        path = Path(output_path)
        path.parent.mkdir(parents=True, exist_ok=True)
        write_bytes_atomic(path, (json.dumps(result, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode())
    return result
